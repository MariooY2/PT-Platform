// PreToolUse guard for Edit, Write and NotebookEdit: path and content policy.
// Worktree-aware: a builder editing .claude/worktrees/<name>/src/x.ts is judged as src/x.ts in that worktree.
// Autopilot-aware: anything that would ask the human is denied with "queue it and move on", so an
// unattended session never stalls on a prompt.
import { existsSync, readFileSync } from 'node:fs';
import { isAbsolute, join, relative, resolve } from 'node:path';
import { tmpdir } from 'node:os';
import { decide, isTracked, projectDir, readInput, toProjectPath, trace } from './lib.mjs';
import { activeScopeIncludes, autopilotOn, isPreapproved } from '../../scripts/lib/autopilot.mjs';

const input = await readInput();
const ti = input?.tool_input ?? {};
const rawPath = ti.file_path ?? ti.notebook_path ?? '';
let p = toProjectPath(rawPath);

function within(base, target) {
  if (!base) return false;
  const r = relative(resolve(base), resolve(target));
  return r === '' || (!r.startsWith('..') && !isAbsolute(r));
}

// Outside the project: only the session scratchpad and the OS temp folder are writable.
if (p === null) {
  if (within(input?.scratchpad_dir, rawPath) || within(tmpdir(), rawPath)) process.exit(0);
  trace(`guard-paths DENY outside ${rawPath}`);
  decide('deny', `Blocked: ${rawPath} is outside the project. Write only inside the project (or the session scratchpad).`);
}

// Builder worktrees: judge the path relative to the worktree root.
let root = projectDir;
let worktree = null;
const wt = p.match(/^\.claude\/worktrees\/([^/]+)\/(.*)$/);
if (wt) { worktree = wt[1]; root = join(projectDir, '.claude', 'worktrees', wt[1]); p = wt[2]; }

const auto = autopilotOn(projectDir);
const QUEUE = 'Autopilot does not wait for answers: add a line to .harness/approvals.md '
  + '("- [ ] <task-id> · <what> · <why> · <exact step for the human>"), do everything else you can, and continue with the next task.';
const deny = (why) => { trace(`guard-paths DENY ${worktree ? `[${worktree}] ` : ''}${p}`); decide('deny', `Blocked: ${why}`); };
const ask = (why) => {
  if (auto) { trace(`guard-paths DENY(autopilot) ${p}`); decide('deny', `Needs the human: ${why} ${QUEUE}`); }
  trace(`guard-paths ASK ${p}`); decide('ask', why);
};
const tracked = (q) => existsSync(join(root, q)) && isTracked(q, root);
const base = p.split('/').pop();

// Content after this edit (Write, Edit or MultiEdit-style replace).
function nextContent(file) {
  const current = existsSync(file) ? readFileSync(file, 'utf8') : '';
  if (typeof ti.content === 'string') return [current, ti.content];
  if (typeof ti.old_string === 'string' && typeof ti.new_string === 'string') {
    return [current, ti.replace_all ? current.split(ti.old_string).join(ti.new_string) : current.replace(ti.old_string, ti.new_string)];
  }
  return [current, current];
}
// Lines removed by the edit (multiset difference).
function removedLines(before, after) {
  const count = new Map();
  for (const l of after.split('\n')) count.set(l, (count.get(l) ?? 0) + 1);
  const removed = [];
  for (const l of before.split('\n')) {
    const n = count.get(l) ?? 0;
    if (n > 0) count.set(l, n - 1); else removed.push(l);
  }
  return removed;
}

if (/^\.env(\..+)?$/.test(base) && base !== '.env.example') deny(`${p} holds secrets. Edit .env.example and let the human set real values.`);
if (p === 'src/lib/supabase/types.ts') deny('src/lib/supabase/types.ts is generated. Change the schema with a migration, then run `pnpm db:types`.');
if (p === 'pnpm-lock.yaml' || p === 'package-lock.json') deny('Lockfiles are generated by the package manager, never edited by hand.');
if (p === '.harness/last-verify.json' || p.startsWith('.harness/trace.log')) deny(`${p} is evidence written only by scripts/verify.mjs and the hooks. Run \`node scripts/verify.mjs\`.`);
if (p === '.harness/autopilot-state.json') deny('The autopilot switch is changed only with `node scripts/autopilot.mjs on|off`.');
if (p === '.harness/autopilot.json') ask('Edits the autopilot policy, which belongs to the human.');
if (/^supabase\/migrations\/.+\.sql$/.test(p) && tracked(p)) {
  deny(`${p} is a committed migration. Create a new one with \`supabase migration new <name>\` instead of editing history.`);
}

// Parallel builders: the orchestrator owns the database lane, run state and the shared UI route list.
if (worktree) {
  if (/^supabase\//.test(p)) deny('Builders do not change the database (migrations, seed). The orchestrator owns the schema lane. Report NEEDS-SCHEMA with the SQL you need.');
  if (/^\.harness\//.test(p)) deny('Run state belongs to the orchestrator. Put facts, decisions, lessons and approvals in your final report.');
  if (p === 'tests/e2e/ui-routes.ts') deny('The orchestrator adds UI routes after merging. List the routes and states in your final report.');
}

// Contracts: status/approval fields may change freely. Otherwise the human approves the edit — except in
// autopilot, where additions (wider scope, extra acceptance lines) are allowed but nothing may be removed.
if (/^tasks\/.+\.ya?ml$/.test(p) && tracked(p)) {
  const [before, after] = nextContent(join(root, p));
  const removed = removedLines(before, after).filter((l) => l.trim() && !/^\s*(status|approved_by|approved_at):/.test(l));
  const added = removedLines(after, before).filter((l) => l.trim() && !/^\s*(status|approved_by|approved_at):/.test(l));
  if (removed.length || (added.length && !auto)) {
    ask(`Edits a committed task contract (${p})${removed.length ? ` and removes or rewrites lines (${removed.slice(0, 2).map((l) => l.trim()).join(' | ')})` : ''}. Acceptance lines must not get weaker.`);
  }
}

// Harness files: changes need the human, so work can't pass by weakening the checks.
if (/^(scripts\/|\.claude\/|\.github\/workflows\/)/.test(p) || ['CLAUDE.md', 'docs/HARNESS.md', '.worktreeinclude'].includes(p)) {
  const ciInScope = auto && !worktree && /^\.github\/workflows\//.test(p) && activeScopeIncludes(projectDir, p);
  if (!ciInScope) ask(`Edits a harness file (${p}). Harness changes go through /harness-upgrade and need approval.`);
}
// Design tokens and UI specs: once committed, the look changes only with the human's say-so.
if ((p === 'src/app/globals.css' || /^docs\/ui\//.test(p)) && tracked(p)) {
  ask(`Edits ${p === 'src/app/globals.css' ? 'the design tokens' : 'a UI spec'} (${p}). Approve only if the human wants this design change; record it in .harness/decisions.md.`);
}

// package.json: new dependencies need approval (in autopilot: only those not pre-approved in the policy).
if (p === 'package.json') {
  const [before, after] = nextContent(join(root, p));
  const deps = (txt) => {
    const j = JSON.parse(txt || '{}');
    return new Set(['dependencies', 'devDependencies', 'optionalDependencies', 'peerDependencies'].flatMap((k) => Object.keys(j[k] ?? {})));
  };
  try {
    const had = deps(before);
    const added = [...deps(after)].filter((d) => !had.has(d));
    const needsHuman = auto ? added.filter((d) => !isPreapproved(projectDir, d)) : added;
    if (needsHuman.length) ask(`Adds dependencies to package.json (${needsHuman.join(', ')}). Check the contract's allowed packages, then approve.`);
  } catch {
    ask('package.json edit could not be parsed as JSON — review it.');
  }
}

process.exit(0);
